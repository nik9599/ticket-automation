#!/usr/bin/env python3
"""Settings + generated project profiles for the ticket automation (stdlib only).

Two layers, neither of them in git:
  settings.json            YOUR input: names, tracker / Slack ids, and per repo: path, ticket matching, test environment.
  projects/<repo>/         GENERATED by step 0 (skills/project_map.md) from a scan of the repo, only with your permission:
                           profile.json (surfaces, commands, local-only files, ...), project.md, <surface>.md.
automation.json (in git) holds only generic defaults. Files use {{KEY}} placeholders for flat settings; run.py fills them.

  python3 config.py check                 # settings complete? repo paths exist? CLIs installed? profiles present / fresh?
  python3 config.py show                  # resolved settings (passwords masked)
  python3 config.py install               # check, then install agents/*.md (if you keep any) into ~/.claude/agents/
  python3 config.py profile <repo> [key]  # print a repo's generated profile (or one key of it)
"""
import json, os, re, shutil, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
SETTINGS = HERE / "settings.json"
EXAMPLE = HERE / "settings.example.json"
PROJECTS = HERE / "projects"
PLACEHOLDER = re.compile(r"\{\{([A-Z0-9_]+)\}\}")
UNSET = ("", "CHANGE_ME")
SECRET_WORDS = ("PASSWORD", "TOKEN", "SECRET")


def settings():
    """settings.json + environment overrides (an env var with the same top-level KEY wins)."""
    if not SETTINGS.exists():
        sys.exit(f"missing {SETTINGS.name}: run  cp settings.example.json settings.json  and fill in your values")
    raw = json.loads(SETTINGS.read_text())
    s = {k: v for k, v in raw.items() if not k.startswith("_")}
    for k in list(s):
        if os.environ.get(k) and not isinstance(s[k], (dict, list)):
            s[k] = os.environ[k]
    s["AUTOMATION_DIR"] = str(HERE)
    s["WATCH_SKILL_DIR"] = s.get("WATCH_SKILL_DIR") or find_watch_skill()
    s["WATCH_ENGINE"] = s.get("WATCH_ENGINE") or "local"
    return s


def find_watch_skill():
    """The `watch` video skill (Claude Code plugin watch@claude-video): newest installed copy, or "" if it is not installed."""
    hits = sorted((Path.home() / ".claude" / "plugins").glob("cache/*/watch/*/skills/watch/scripts/watch.py"))
    return str(hits[-1].parent.parent) if hits else ""


def render(text, s=None):
    """Replace every {{KEY}} with its flat setting; unknown keys stay as they are."""
    s = s or settings()
    return PLACEHOLDER.sub(lambda m: str(s[m.group(1)]) if m.group(1) in s and not isinstance(s[m.group(1)], (list, dict)) else m.group(0), text)


def _render_obj(o, s):
    if isinstance(o, str):
        return render(o, s)
    if isinstance(o, list):
        return [_render_obj(x, s) for x in o]
    if isinstance(o, dict):
        return {k: _render_obj(v, s) for k, v in o.items()}
    return o


def profile_path(repo):
    return PROJECTS / repo / "profile.json"


def load_profile(repo):
    p = profile_path(repo)
    try:
        return json.loads(p.read_text()) if p.exists() else {}
    except ValueError:
        return {}


def load_repos():
    """automation.json defaults + tracker, with each settings.json repo merged with its generated profile."""
    s = settings()
    cfg = _render_obj(json.loads((HERE / "automation.json").read_text()), s)
    cfg["repos"] = {}
    for name, rc in (s.get("repos") or {}).items():
        if name.startswith("_"):
            continue
        rc = dict(rc)
        rc["enabled"] = rc.get("enabled", True)
        prof = load_profile(name)
        rc["profile"] = prof
        rc["base_branch"] = rc.get("base_branch") or prof.get("base_branch") or cfg["defaults"].get("base_branch", "main")
        rc["project_dir"] = str(PROJECTS / name)
        cfg["repos"][name] = rc
    return cfg


def settings_block():
    """Appended to every step's system prompt so {{KEY}} in files the agent reads itself can be resolved."""
    s = settings()
    lines = [f"- {{{{{k}}}}} = {v}" for k, v in s.items() if not isinstance(v, (list, dict))]
    return ("## Settings (from settings.json)\nAny {{KEY}} you see in a file of this automation means the value below. "
            "Per-repo values (path, ticket matching, test environment, generated profile) are in the repo config given in the prompt.\n"
            + "\n".join(lines))


# ---------- step 0: project profile freshness + scan permission ----------

def _git_ok(repo_path, *args):
    return subprocess.run(["git", "-C", repo_path, *args], capture_output=True, text=True).returncode == 0


def _git(repo_path, *args):
    r = subprocess.run(["git", "-C", repo_path, *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def profile_paths(prof):
    paths = [v.get("code") for v in (prof.get("surfaces") or {}).values() if isinstance(v, dict) and v.get("code")]
    paths += list(prof.get("context_docs") or [])
    return [p.rstrip("/") for p in paths if p]


def profile_status(name, rc, max_age_days):
    """('ok' | 'missing' | 'stale', reason). Checked at the start of every run."""
    prof = rc.get("profile") or {}
    if not prof or not (PROJECTS / name / "project.md").exists():
        return "missing", "no project profile yet (first run)"
    age = (time.time() - profile_path(name).stat().st_mtime) / 86400
    if age > max_age_days:
        return "stale", f"profile is {age:.0f} days old (limit {max_age_days})"
    head = _git(rc["path"], "rev-parse", f"origin/{rc.get('base_branch', 'main')}")
    if not head:
        return "ok", "fresh (origin branch not found locally, path check skipped)"
    missing = [p for p in profile_paths(prof) if not _git_ok(rc["path"], "cat-file", "-e", f"{head}:{p}")]
    if missing:
        return "stale", f"{len(missing)} path(s) in the profile no longer exist on origin (e.g. {missing[0]})"
    scanned = prof.get("scanned_commit", "")
    if scanned and scanned != head and _git_ok(rc["path"], "cat-file", "-e", scanned):
        changed = _git(rc["path"], "diff", "--name-only", scanned, head).splitlines()
        if len(changed) > int(rc.get("rescan_after_changed_files", 300)):
            return "stale", f"{len(changed)} files changed since the last scan"
    return "ok", "fresh"


def scan_permission(name, rc, reason):
    """SCAN_PERMISSION in settings: ask (default) | always | never. Asking needs a terminal; otherwise no scan."""
    mode = str(settings().get("SCAN_PERMISSION", "ask")).lower()
    if mode == "always":
        return True
    if mode == "never":
        return False
    if not sys.stdin.isatty():
        print(f"  {name}: scan needed ({reason}) but there is no terminal to ask. Run  python3 run.py --map {name}  "
              "in a terminal, or set SCAN_PERMISSION to always in settings.json.")
        return False
    print(f"\n  Repo '{name}' ({rc['path']}): {reason}.")
    print("  Step 0 will READ this repo with Claude (docs, folder tree, package scripts, git history of origin) and write")
    print(f"  {PROJECTS / name}/ (profile.json, project.md, one map per surface). Nothing in the repo is changed.")
    try:
        ans = input("  Allow the scan? [y/N] ").strip().lower()
    except EOFError:
        ans = ""
    return ans in ("y", "yes")


# ---------- checks ----------

def check():
    """Return a list of problems (empty = ready)."""
    if not SETTINGS.exists():
        return [f"{SETTINGS.name} missing: cp settings.example.json settings.json"]
    problems = []
    s = settings()
    example = json.loads(EXAMPLE.read_text()) if EXAMPLE.exists() else {}
    for k, v in example.items():
        if k.startswith("_"):
            continue
        if k not in s:
            problems.append(f"{k}: missing in settings.json (see settings.example.json)")
        elif isinstance(s[k], str) and s[k].strip() in UNSET and v == "CHANGE_ME":
            problems.append(f"{k}: not filled in")
    cfg = load_repos()
    enabled = {n: rc for n, rc in cfg["repos"].items() if rc.get("enabled")}
    if not enabled:
        problems.append("no enabled repo in settings.json -> repos")
    for name, rc in enabled.items():
        path = str(rc.get("path", ""))
        if not Path(path).is_dir():
            problems.append(f"repo '{name}': path does not exist: {path}")
        elif not (Path(path) / ".git").exists():
            problems.append(f"repo '{name}': {path} is not a git checkout")
        m = rc.get("ticket_match") or {}
        if not (m.get("title_prefixes") or m.get("tags")):
            problems.append(f"repo '{name}': ticket_match needs title_prefixes or tags")
        url = str((rc.get("test_environment") or {}).get("url", "")).strip()
        if url in UNSET:
            problems.append(f"repo '{name}': test_environment.url not filled in (the only place the automation may change anything)")
    leftovers = set()
    for f in [HERE / "guardrails.md", HERE / "pipeline.json", HERE / "automation.json", *HERE.glob("skills/**/*.md")]:
        leftovers |= {k for k in PLACEHOLDER.findall(f.read_text()) if k not in s}
    if leftovers:
        problems.append("placeholders with no setting: " + ", ".join(sorted(leftovers)))
    watch = s.get("WATCH_SKILL_DIR", "")
    if not watch:
        problems.append("`watch` video skill not installed: in Claude Code run  /plugin marketplace add bradautomates/claude-video  then "
                        "/plugin install watch@claude-video, then /watch once to finish its setup (or set WATCH_SKILL_DIR)")
    elif subprocess.run([sys.executable, str(Path(watch) / "scripts" / "setup.py"), "--check"], capture_output=True).returncode != 0:
        problems.append("`watch` skill is installed but not set up: run /watch once in an interactive Claude Code session "
                        "(engine local is enough; ffmpeg + yt-dlp are needed)")
    for tool, why in (("claude", "install Claude Code"), ("gh", "needed for draft PRs"), ("git", "")):
        if not shutil.which(tool):
            problems.append(f"`{tool}` not found on PATH" + (f" ({why})" if why else ""))
    return problems


def install_agents():
    if not (HERE / "agents").is_dir():
        print("no agents/ folder: nothing to install"); return
    dest = Path.home() / ".claude" / "agents"
    dest.mkdir(parents=True, exist_ok=True)
    s = settings()
    for f in sorted((HERE / "agents").glob("*.md")):
        if f.name.lower() != "readme.md":
            (dest / f.name).write_text(render(f.read_text(), s))
            print(f"installed agent {f.stem} -> {dest / f.name}")


def _mask(k, v):
    return "********" if any(w in k.upper() for w in SECRET_WORDS) and v else v


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "show":
        for k, v in settings().items():
            if k == "repos":
                for n, rc in v.items():
                    te = {tk: _mask(tk, tv) for tk, tv in (rc.get("test_environment") or {}).items()}
                    print(f"repo {n}: path={rc.get('path')} enabled={rc.get('enabled', True)} test_environment={te}")
            else:
                print(f"{k} = {_mask(k, v)}")
        return
    if cmd == "profile":
        if len(sys.argv) < 3:
            sys.exit("usage: config.py profile <repo> [key]")
        prof = load_profile(sys.argv[2])
        val = prof.get(sys.argv[3], "") if len(sys.argv) > 3 else prof
        print(val if isinstance(val, str) else json.dumps(val, indent=2))
        return
    if cmd in ("check", "install"):
        problems = check()
        for p in problems:
            print("  - " + p)
        if problems:
            sys.exit(f"{len(problems)} problem(s); fix settings.json and run again")
        print("settings OK")
        cfg = load_repos()
        days = int(cfg["defaults"].get("profile_max_age_days", 14))
        for name, rc in cfg["repos"].items():
            if rc.get("enabled"):
                st, why = profile_status(name, rc, days)
                print(f"  project profile {name}: {st} ({why})" + ("" if st == "ok" else f" -> python3 run.py --map {name}"))
        if cmd == "install":
            install_agents()
        return
    sys.exit(__doc__)


if __name__ == "__main__":
    main()
