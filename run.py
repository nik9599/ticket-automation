#!/usr/bin/env python3
"""Ticket automation orchestrator (stdlib only).

  python3 run.py                 # fetch + every enabled step, every enabled repo
  python3 run.py --dry-run       # print what it would run
  python3 run.py --repo my-app --step replicate --limit 2
  python3 run.py --board         # show ticket states
  python3 run.py --map my-app   # (re)scan that repo into projects/my-app/ (step 0; asks permission; also runs by itself when missing/stale)
  python3 run.py --ticket <ticket-id> [--requeue]   # only this ticket (adds it via fetch if new)

Light by design: ONE claude session at a time, one ticket per session, one repo at a time, waits when the machine is busy.
Stop it any time with:  touch STOP   (in this folder)
"""
import argparse, json, os, shlex, subprocess, sys, time, uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import config  # settings.json: every user-specific value ({{KEY}} in prompts/config)
STATE = HERE / "state"
LOCK = STATE / ".lock"
STOP = HERE / "STOP"
LEDGER = [sys.executable, str(HERE / "ledger.py")]
LOCK_MAX_HOURS = 6


def jload(name):
    return config.load_repos() if name == "automation.json" else json.loads((HERE / name).read_text())


def ledger(*args):
    return subprocess.run(LEDGER + list(args), capture_output=True, text=True, env=os.environ).stdout.strip()


def take_lock(force=False):
    STATE.mkdir(parents=True, exist_ok=True)
    if LOCK.exists():
        try:
            info = json.loads(LOCK.read_text())
            age_h = (time.time() - info["ts"]) / 3600
            alive = True
            try:
                os.kill(info["pid"], 0)
            except OSError:
                alive = False
            if alive and age_h < LOCK_MAX_HOURS and not force:
                sys.exit(f"another run is active (pid {info['pid']}, {age_h:.1f}h). Remove {LOCK} if that is wrong.")
        except Exception:
            pass
    LOCK.write_text(json.dumps({"pid": os.getpid(), "ts": time.time()}))


def release_lock():
    try:
        LOCK.unlink()
    except FileNotFoundError:
        pass


def wait_if_busy(cfg, dry):
    cores = os.cpu_count() or 4
    limit = cores * float(cfg["defaults"].get("max_load_per_core", 0.8))
    waited = 0
    while not dry and os.getloadavg()[0] > limit and waited < 30:
        print(f"  machine busy (load {os.getloadavg()[0]:.1f} > {limit:.1f}); waiting 1 min")
        time.sleep(60); waited += 1


def log_timing(step, repo, ticket, secs, rc):
    """One line per claude session in state/timings.csv (feeds the digest)."""
    try:
        f = STATE / "timings.csv"
        new = not f.exists()
        with open(f, "a") as fh:
            if new:
                fh.write("time,step,repo,ticket,seconds,returncode\n")
            fh.write(f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')},{step},{repo},{ticket or 'all'},{secs:.0f},{rc}\n")
    except OSError:
        pass


def audit_ok(repo_name, rc, ticket, step_name):
    """Guardrail audit after fix/verify (tools/audit.py). On a violation the ticket goes to needs-human and the run stops."""
    r = subprocess.run([sys.executable, str(HERE / "tools" / "audit.py"), "--repo", repo_name, "--repo-path", rc["path"], "--ticket", ticket, "--step", step_name],
                       capture_output=True, text=True, env=dict(os.environ, TICKET_REPO=repo_name, TICKET_BASE_BRANCH=rc.get("base_branch", "main")))
    print("  " + (r.stdout + r.stderr).strip().replace("\n", "\n  "))
    if r.returncode != 0:
        ledger("set", ticket, "--stage", "needs-human", "--force", "--note",
               f"GUARDRAIL AUDIT FAILED after {step_name}: " + (r.stdout + r.stderr).strip().replace("\n", " | ")[:600])
        return False
    return True


def make_digest():
    try:
        r = subprocess.run([sys.executable, str(HERE / "tools" / "digest.py")], capture_output=True, text=True)
        print("== digest written to state/digest-latest.md")
        print(r.stdout[:3000])
    except Exception as e:
        print(f"  (digest failed: {e})")


def run_claude(step, repo_name, repo_cfg, cwd, prompt, ticket, cfg, dry):
    s = config.settings()
    sub = lambda t: config.render(t, s)
    guard = (HERE / "guardrails.md").read_text()
    skill = (HERE / step["skill"]).read_text()
    sysprompt = sub(guard + "\n\n" + skill) + "\n\n" + config.settings_block()
    prompt = sub(prompt)
    cmd = ["claude", "-p", prompt, "--append-system-prompt", sysprompt, "--max-turns", str(step.get("max_turns", 60)), "--add-dir", str(HERE)]
    if step.get("model"):
        cmd += ["--model", step["model"]]
    tools = list(step.get("allowed_tools") or [])
    if step.get("profile_tools"):   # the repo's own commands, generated by step 0 (e.g. its test / lint / start scripts)
        tools += [t for t in ((repo_cfg or {}).get("profile") or {}).get("extra_allowed_tools", []) if t.startswith("Bash(") and "sudo" not in t and " rm " not in t]
    if tools:
        cmd += ["--allowedTools", ",".join(sub(t) for t in tools)]
        if any(t.startswith("mcp__claude-in-chrome__") for t in tools):
            cmd += ["--chrome"]   # headless sessions get no Chrome tools without this flag
    if ticket and not dry:
        # own session id, so cleanup deletes this transcript once the ticket's draft PR is done
        sid = str(uuid.uuid4()); cmd += ["--session-id", sid]
        ledger("set", ticket, "--session", f"{sid}|{cwd}")
    elif not ticket:
        cmd += ["--no-session-persistence"]   # fetch: nothing worth keeping
    env = dict(os.environ, TICKET_REPO=repo_name, TICKET_AUTOMATION_DIR=str(HERE))
    if repo_cfg and repo_name != "all":
        te = repo_cfg.get("test_environment") or {}
        prof = repo_cfg.get("profile") or {}
        env.update(TICKET_BASE_BRANCH=repo_cfg.get("base_branch", "main"), TICKET_PROJECT_DIR=repo_cfg.get("project_dir", ""),
                   TEST_BASE_URL=str(te.get("url", "")), TEST_HOST=str(te.get("host", "")),
                   GUARD_ACTION_WORDS=",".join(prof.get("guard_action_words") or []))
    if ticket:
        env["TICKET_ID"] = ticket
    label = f"{step['name']}:{repo_name}:{ticket or 'all'}"
    if dry:
        print(f"[dry-run] cwd={cwd} {label}\n          claude -p {shlex.quote(prompt[:100])} ... --model {step.get('model','default')} --allowedTools ({len(step.get('allowed_tools', []))} rules)")
        return 0
    logs = STATE / "logs"; logs.mkdir(parents=True, exist_ok=True)
    logf = logs / f"{time.strftime('%Y%m%d-%H%M%S')}-{step['name']}-{repo_name}-{ticket or 'all'}.log"
    print(f"  -> {label}  (log: {logf.name})")
    t0 = time.time()
    try:
        with open(logf, "w") as f:
            r = subprocess.run(cmd, cwd=cwd, env=env, stdout=f, stderr=subprocess.STDOUT, timeout=step.get("timeout_min", 30) * 60)
        log_timing(step["name"], repo_name, ticket, time.time() - t0, r.returncode)
        return r.returncode
    except subprocess.TimeoutExpired:
        log_timing(step["name"], repo_name, ticket, time.time() - t0, 124)
        print(f"  !! timeout on {label}")
        if ticket:
            ledger("set", ticket, "--note", f"step {step['name']} timed out")
        return 124
    except FileNotFoundError:
        sys.exit("`claude` CLI not found on PATH. Run this on the machine where Claude Code is installed.")


REQUEUE_FROM = ("skipped", "needs-info", "failed")


def ticket_info(tid):
    out = ledger("show", tid)
    try:
        return json.loads(out)
    except ValueError:
        return None


def ticket_summary(tid):
    t = ticket_info(tid)
    if not t:
        return f"{tid}: not in ledger"
    note = (t["history"][-1].get("note") or "")[:300] if t.get("history") else ""
    return f"{tid} [{t['repo']}] stage={t['stage']}" + (f" pr={t['pr_url']}" if t.get("pr_url") else "") + (f" | {note}" if note else "")


def prepare_ticket(a, cfg, pipe, repos):
    """--ticket: make sure the ticket is in the ledger (single-ticket fetch) and runnable; return {its repo: cfg}."""
    tid = a.ticket
    if not __import__("re").fullmatch(r"[A-Za-z0-9]+", tid):
        sys.exit(f"bad ticket id: {tid!r}")
    if ledger("known", tid) != "yes":
        step = next(s for s in pipe["steps"] if s["name"] == "fetch")
        first = next(iter(repos.values()))
        prompt = (f"SINGLE-TICKET MODE: {{{{OWNER_NAME}}}} asked for ClickUp ticket {tid} only. Skip step 0 (reconcile), batch_size/room and ranking. "
                  f"Do only this: read the ticket (clickup_get_task {tid}); if its status is not the config status, add nothing and report the status. "
                  "Otherwise apply every drop/skip rule of step 3 to it (a skip is recorded with `ledger.py add` + `--stage skipped --note <why>` as usual), "
                  "map it to a repo with step 4 (plus the UNMAPPED RESCUE), and if it passes run the step 6 `ledger.py add` + FOCUS note. "
                  "End with one line: ADDED <repo> / SKIPPED <why> / NOT ADDED <why>.\nConfig:\n"
                  + json.dumps({"defaults": cfg["defaults"], "clickup": cfg["clickup"], "repos": repos}, indent=2))
        print(f"== single-ticket fetch {tid}")
        wait_if_busy(cfg, a.dry_run)
        run_claude(step, "all", first, first["path"], prompt, tid, cfg, a.dry_run)
        if a.dry_run:
            return repos
        if ledger("known", tid) != "yes":
            sys.exit(f"ticket {tid} was NOT added (wrong status, unmapped or fetch failed); see the latest fetch log in state/logs")
    t = ticket_info(tid)
    if t["stage"] in REQUEUE_FROM:
        if not a.requeue:
            sys.exit(f"ticket not run: {ticket_summary(tid)}. Use --requeue (Slack: 'force handle <url>') to queue it again.")
        ledger("set", tid, "--stage", "queued", "--note", "requeued on request (single-ticket run)")
    elif t["stage"] in ("needs-human", "done", "done-config", "done-be", "moved-out", "pr-draft", "preprod-wait", "preprod-verified"):
        sys.exit(f"ticket not run (nothing to do automatically): {ticket_summary(tid)}")
    if t["repo"] not in repos:
        sys.exit(f"ticket {tid} belongs to repo '{t['repo']}', which is not enabled")
    return {t["repo"]: repos[t["repo"]]}


def ensure_project_maps(a, cfg, pipe, repos, only=None):
    """Step 0 (every run): each repo's generated profile must exist and be fresh; (re)scan only with the owner's permission.
    Returns the repos that can run this time (a repo with no profile and no permission is skipped)."""
    step = next((s for s in pipe["steps"] if s["name"] == "project_map"), None)
    if not step or not step.get("enabled"):
        return repos
    days = int(cfg["defaults"].get("profile_max_age_days", 14))
    ready = {}
    for name, rc in repos.items():
        if only and name != only:
            continue
        status, why = config.profile_status(name, rc, days)
        if only and status == "ok":
            status, why = "stale", "rescan requested (--map)"
        if status == "ok":
            ready[name] = rc; continue
        if a.dry_run:
            print(f"[dry-run] step project_map {name}: {why} (would ask permission to scan)")
            ready[name] = rc; continue
        if not config.scan_permission(name, rc, why):
            if status == "stale":
                print(f"  {name}: scan not allowed, using the existing profile ({why})"); ready[name] = rc
            else:
                print(f"  {name}: skipped this run: no project profile and no scan permission")
            continue
        print(f"== step project_map {name} ({why})")
        wait_if_busy(cfg, a.dry_run)
        (HERE / "projects" / name).mkdir(parents=True, exist_ok=True)
        prompt = (f"Build the project profile for repo '{name}' now. Today is {time.strftime('%Y-%m-%d')}. "
                  f"project_dir = {rc['project_dir']}. Repo config:\n" + json.dumps(rc, indent=2))
        run_claude(step, name, rc, rc["path"], prompt, None, cfg, a.dry_run)
        fresh = config.load_repos()["repos"][name]
        if not fresh.get("profile"):
            print(f"  {name}: step 0 wrote no valid profile.json; skipped this run (see the latest project_map log in state/logs)"); continue
        ready[name] = fresh
    return ready


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo"); ap.add_argument("--step"); ap.add_argument("--limit", type=int)
    ap.add_argument("--dry-run", action="store_true"); ap.add_argument("--board", action="store_true")
    ap.add_argument("--no-fetch", action="store_true"); ap.add_argument("--cleanup", action="store_true", help="only delete logs/evidence/worktrees of finished tickets"); ap.add_argument("--force-lock", action="store_true")
    ap.add_argument("--ticket", help="run only this ClickUp ticket id (fetch adds it first if it is not in the ledger)")
    ap.add_argument("--requeue", action="store_true", help="with --ticket: put a skipped/needs-info/failed ticket back to queued")
    ap.add_argument("--map", metavar="REPO", help="only (re)scan this repo into projects/<repo>/ (step 0, asks permission), then exit")
    a = ap.parse_args()
    if a.board:
        print(ledger("board")); print(ledger("disk")); return
    if a.cleanup:
        print(ledger("cleanup", *(["--dry-run"] if a.dry_run else []))); return
    cfg, pipe = jload("automation.json"), jload("pipeline.json")
    repos = {k: v for k, v in cfg["repos"].items() if not k.startswith("_") and v.get("enabled")}
    if a.repo:
        repos = {k: v for k, v in repos.items() if k == a.repo}
    if not repos:
        sys.exit("no enabled repos matched")
    for k, v in repos.items():
        if not Path(v["path"]).is_dir():
            if a.dry_run:
                print(f"warning: repo path for {k} not found here: {v['path']}")
            else:
                sys.exit(f"repo path for {k} does not exist: {v['path']}")
    if STOP.exists():
        sys.exit("STOP file present; remove it to run.")
    problems = config.check()
    if problems and not a.dry_run:
        sys.exit("setup not complete (python3 config.py check):\n  - " + "\n  - ".join(problems))
    if not a.dry_run:
        take_lock(a.force_lock)
    if a.map:   # scan only: no batch note, no digest, no cleanup
        try:
            if a.map not in repos:
                sys.exit(f"--map: '{a.map}' is not an enabled repo in settings.json")
            ensure_project_maps(a, cfg, pipe, repos, only=a.map); return
        finally:
            if not a.dry_run:
                release_lock()
    if not a.dry_run:
        print(ledger("batch", "start"))   # Apple Notes "Batch-N · date": tickets that need the owner, per step
    try:
        repos = ensure_project_maps(a, cfg, pipe, repos)
        if not repos:
            print("== no repo has a project profile; nothing to run"); return
        ledger("recover", "--minutes", "90")
        if a.ticket:
            repos = prepare_ticket(a, cfg, pipe, repos)
        for step in pipe["steps"]:
            if not step.get("enabled") or step["scope"] == "setup" or (a.step and a.step != step["name"]):
                continue
            if step["name"] == "fetch" and (a.no_fetch or a.ticket):
                continue
            print(f"== step {step['name']}")
            if step["scope"] == "global":
                first = next(iter(repos.values()))
                prompt = "Run the fetch step now.\nConfig:\n" + json.dumps({"defaults": cfg["defaults"], "clickup": cfg["clickup"], "repos": repos}, indent=2)
                wait_if_busy(cfg, a.dry_run)
                run_claude(step, "all", first, first["path"], prompt, None, cfg, a.dry_run)
                continue
            for name, rc in repos.items():
                ids = ledger("next", "--repo", name, "--stages", ",".join(step["from_stages"]), *(["--limit", str(a.limit)] if a.limit else [])).split()
                if a.ticket:
                    ids = [i for i in ids if i == a.ticket]
                if not ids:
                    print(f"  {name}: nothing for {step['name']}"); continue
                for tid in ids:
                    if STOP.exists():
                        print("STOP file found; stopping."); return
                    wait_if_busy(cfg, a.dry_run)
                    prompt = (f"Run the {step['name']} step for ClickUp ticket {tid} in repo '{name}'. "
                              "Ledger: python3 {{AUTOMATION_DIR}}/ledger.py. Project files: " + rc.get("project_dir", "") + ". Repo config:\n" + json.dumps(rc, indent=2))
                    run_claude(step, name, rc, rc["path"], prompt, tid, cfg, a.dry_run)
                    if step["name"] in ("fix", "verify") and not a.dry_run and not audit_ok(name, rc, tid, step["name"]):
                        print("== guardrail audit FAILED; stopping the run (ticket set to needs-human)")
                        return
        print(ledger("board", *(["--repo", next(iter(repos))] if a.ticket else [])))
        if a.ticket:
            print("== ticket " + ticket_summary(a.ticket))
        if not a.dry_run:
            print(ledger("batch", "finish"))   # analytics note, before cleanup compacts the findings
            print("== cleanup (finished tickets)"); print(ledger("cleanup"))
    finally:
        if not a.dry_run:
            ledger("batch", "finish")   # no-op when already finished; closes the batch if the run stopped early
            make_digest()
            release_lock()


if __name__ == "__main__":
    main()
